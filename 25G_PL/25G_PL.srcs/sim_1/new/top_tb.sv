`timescale 1ns / 1ps

module top_tb();

    // --------------------------------------------------------
    // 信号声明
    // --------------------------------------------------------
    logic        i_clk_50m;    // 50MHz 系统时钟
    logic        i_rst;        // low电平复位
    logic [11:0] i_ad_data;    // 模拟 AD 输入数据

    logic [13:0] o_da_data;    // DA 输出数据
    logic        o_da_wrt;     // DA 写使能时钟

    // --------------------------------------------------------
    // 例化顶层模块 H_top
    // --------------------------------------------------------
    H_top u_H_top (
        .i_clk_50m  (i_clk_50m),
        .i_rst      (i_rst),
        .i_ad_data  (i_ad_data),
        .o_da_data  (o_da_data),
        .o_da_wrt   (o_da_wrt)
    );

    // --------------------------------------------------------
    // 生成系统时钟 (50MHz = 20ns 周期)
    // --------------------------------------------------------
    initial begin
        i_clk_50m = 0;
        forever #10 i_clk_50m = ~i_clk_50m;
    end

    // --------------------------------------------------------
    // 模拟 AD 输入数据 (生成一个简单的锯齿波测试数据)
    // --------------------------------------------------------
    // 注意：实际的 AD 数据是随着内部 65MHz 时钟采样的
    // 这里为了测试简便，使用 50MHz 时钟驱动模拟数据，但在真实的验证环境中
    // 可以从 UUT 内部引出 65MHz 的时钟来驱动这个测试数据的生成
    always_ff @(posedge i_clk_50m or negedge i_rst) begin
        if (!i_rst) begin
            i_ad_data <= 12'd0;
        end else begin
            // 累加生成 0 ~ 4095 的循环数据
            i_ad_data <= i_ad_data + 1'b1;
        end
    end

    // --------------------------------------------------------
    // 测试激励流程控制
    // --------------------------------------------------------
    initial begin
        // 1. 初始化
        i_rst = 1'b0;
        
        // 2. 保持复位一段时间，等待系统稳定
        #100;
        
        // 3. 释放复位
        i_rst = 1'b1;

        // 4. 等待足够长的时间以观察 FIFO 写满、RAM 乒乓切换和 DA 输出
        // FFT_LENGTH 是 4096，65MHz 下写满大约需要 63us，这里跑 200us
        #200000;
        
        // 5. 结束仿真
        $display("Simulation Finished!");
        $finish;
    end

endmodule